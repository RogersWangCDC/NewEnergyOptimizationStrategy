cfg.pso.twoStage     = true;  % true  => 阶段 A 典型日粗搜 + 阶段 B 目标口径精搜
                              % false => 只按 cfg.time.mode 单阶段搜索
cfg.pso.stageA.nPop    = 60;  % 阶段 A 粒子数
cfg.pso.stageA.maxIter = 100; % 阶段 A 迭代次数
cfg.pso.stageA.K       = 12;  % 阶段 A 用的典型日个数 K（12 x 24 = 288 h）
cfg.pso.stageA.shrink  = 0.50;% 阶段 B 起始搜索区间 = 以 A 解为中心的收缩框，
