                              % 0 = 关闭（默认）。开启后总耗时约放大 multiRun 倍。

% ---- 搜索范围 [光伏 ; 风电 ; 储能功率 ; 储能时长(h) ; 自发电容量]，MW / MW / MW / h / MW ----
% ★ 固定某个维度 => 令 lb(k) = ub(k)（或用下面的 cfg.fixed 结构体）
