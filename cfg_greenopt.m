cfg.fixed.gen  = [];    % MW  厂内自发电容量（填 0 = 不建自发电，完全等价旧版行为）

%% ==================== 6. 内层 MILP (intlinprog) ====================
cfg.milp.useBinary = true;   % 购/售电互斥 0-1 变量（防止同时购电与售电套利）
                             % ⚠ 这一项**不能关**，即使只是想加速搜索：
                             %   本数据集有 89 个小时「售电价 > 购电价」（最大倒挂
                             %   0.0298 元/kWh）。去掉互斥后 LP 会在这些小时同时买电与
