function cfg = cfg_greenopt()
%CFG_GREENOPT  新能源场站「最优配置搜索 + 最优调度」双层模型 —— 参数总配置
%==========================================================================
%  这是整个项目【唯一需要日常修改】的参数文件。
%  配套运行文件：run_greenopt.m（与 Dataset.xlsx 放在同一文件夹）
%--------------------------------------------------------------------------
%  使用步骤
%    (1) 改 Dataset.xlsx 里的数值（列名必须保持为：
%        Buy_Price  Sell_Price  Load  PV_pu  WT_pu  Gen）
%        ⚠ 其中 PV_pu / WT_pu / Gen 三列都应填「标幺出力」（0 ~ 1）；
%          Gen 列若不是标幺而是 MW，请把第 0b 节的 cfg.data.genMode 改成 'mw'。
%    (2) 在本文件里改投资成本 / 搜索范围 / 储能参数
%    (3) 命令行输入 run_greenopt 运行
%--------------------------------------------------------------------------
%  出图清单（全部输出到 results/，每张图可用 cfg.out.plotFigures 单独开关）
%    fig_pso_convergence        外层搜索收敛曲线
%    fig_typical_days_* / fig_fy_*   典型日 源荷曲线 / 出力堆叠图 / 储能 SOC
%    fig_typical_week           典型周调度结果
%    fig_cost_breakdown         成本构成（含自发电投资与运行成本两根柱）
%    fig_pro_metrics            专业化指标对比（LCOE / 比例，默认关闭，见第 3b 节）
%    fig_sensitivity            敏感性分析（8 子图，含自发电容量两格，见第 7b 节）
%--------------------------------------------------------------------------
%  优化变量（外层 PSO 搜索 5 维）
%        s = [ 光伏容量(MW) ; 风电容量(MW) ; 储能功率(MW) ; 储能时长(h) ; 自发电容量(MW) ]
%        储能容量(MWh) = 储能功率(MW) x 储能时长(h)
%        自发电出力(t) = 自发电容量(MW) x Gen_pu(t)   （Gen 列已改为「标幺出力」）
%  内层：intlinprog 求当前配置下的小时级最优调度
%        （含自发电燃料成本；弃电按「光伏 / 风电 / 自发电」分源建模）
%  目标：年化用电成本最低 = 年化投资成本 + 年化最优运行成本
%  成本公式（★ 本轮补充调整，见第 2 节）：
%        年化投资成本 = 容量 x 单位投资单价 x （资金回收系数 CRF + 年运维费率）
%        其中「单位投资单价」由 cfg.cost.mode 决定：
%          'flat'   常数单价（旧口径，便于与历史结果对照）
%          'tiered' 分档单价 —— 按容量在 cfg.cost.*.tier 上分段线性插值，
%                              >= 表中倒数第二个档位（500）时取最后一档的单价
%        分档只对 光伏 / 风电 / 储能功率 / 储能容量 四项生效；
%        厂内自发电没有分档表，恒为常数单价。
%        口径唯一实现：gopt_unit_price（run_greenopt.m），别处一律调用它。
%--------------------------------------------------------------------------
%  只做「内层最优调度」（配置已知）—— 两种等效写法
%    写法一（推荐，直接在这里改）：
%        cfg.fixed.pv   = 30;   % 光伏固定 30 MW
%        cfg.fixed.wt   = 20;   % 风电固定 20 MW
%        cfg.fixed.essP = 10;   % 储能功率固定 10 MW
%        cfg.fixed.essT = 2;    % 储能时长固定 2 h  => 容量 20 MWh
%    写法二（等价，令搜索上下限相等）：
%        cfg.pso.lb = [30; 20; 10; 2];
%        cfg.pso.ub = [30; 20; 10; 2];
%    四个维度全部固定时，程序自动跳过 PSO，只求一次最优调度。
%--------------------------------------------------------------------------
%  单位约定：容量 MW / MWh，时长 h，电价 元/kWh，成本 元，时间步长 1 h
%            投资单价 元/kW（功率类）或 元/kWh（能量类），已含税
%==========================================================================

%% ==================== 0. 路径 ====================
cfg.path.root     = fileparts(mfilename('fullpath')); % 本文件所在目录（= Dataset.xlsx 所在目录）
cfg.path.dataFile = '';                  % 留空 => 自动使用 <本目录>\Dataset.xlsx
cfg.path.sheet    = 'BasicData';         % 工作表名
cfg.path.outDir   = fullfile(cfg.path.root, 'results');   % 结果输出目录

%% ==================== 0b. 数据口径 ====================
cfg.data.genMode = 'pu';   % Gen 列（厂内自发电）的含义：
                           %   'pu' 标幺出力（当前数据，取值 0 ~ 1）：
                           %        实际出力(t) = 自发电容量(MW) x Gen 列(t)，
                           %        自发电容量是第 5 维优化变量。
                           %   'mw' 直接给 MW（旧版数据）：
                           %        实际出力就是 Gen 列原值；程序把第 5 维锁成 1 当作
                           %        「单位容量」，于是 1 x Gen = Gen，行为与旧版完全一致。
                           %   ⚠ 换数据集时先确认这一项：填错会让自发电量级整体差一个数量级。

%% ==================== 1. 时间尺度与场景 ====================
cfg.time.mode         = 'full_year';  % 'typical_days' 典型日(快，默认) | 'full_year' 全年8760h(慢，精度最高)
cfg.time.nTypicalDays = 6;              % 典型日个数 K
                                        %   typical_days 模式：K 个典型日就是内层 MILP 的调度场景本身；
                                        %   full_year   模式：K 仅用于「出图用聚类」——从 8760 h 的
                                        %     全年优化结果里挑出 K 个真实代表日来出典型日图，
                                        %     不影响优化（不额外求解，聚类耗时约 1~2 s）。
cfg.time.repMethod    = 'mean';          % 典型日代表曲线：'mean' 簇内均值 | 'medoid' 簇内真实最近日
cfg.time.typDaySort   = 'median';         % 典型日出图顺序（按日期的排序键）：
                                         %   'median' 按簇内成员自然日的中位数升序（默认，推荐）
                                         %   'mean'   按簇内成员自然日的均值升序
                                         %   'first'  按簇内最早自然日升序
                                         %   'repday' 按「真实代表日」升序（与 full_year 的显示量一致）
                                         %   'none'   不按日期排序，保持 k-means 原始簇序（代表天数降序）
                                         %   注：full_year 模式显示的是 repDay，故该模式**忽略本项**、
                                         %   自动改按 repDay 升序，保证「编号顺序 = 图上日期顺序」；
                                         %   本项实际只决定 typical_days 模式的编号顺序。
                                         %   注：k-means 按负荷/光伏/风电/电价形态聚类，本身不含时间约束，
                                         %   因此多数簇的自然日是全年分散的。实测本数据集 K=6 时，
                                         %   各簇中位日 = 104/184/192/220/286/355 天，用中位日排序
                                         %   能得到「春 -> 冬」的自然顺序；用「最早自然日」排序则退化为
                                         %   1/4/7/9/29/349 天（几乎等于随机），故不作默认。
cfg.time.dt           = 1;               % 时间步长 [h]
cfg.time.loadRepair   = false;            % 是否修复「零负荷」数据缺口
                                         %   本数据集末尾有 312 h 连续零负荷（物理上不可能），
                                         %   判为缺失，用「同时刻有效日中位数」填补。
                                         %   若确为真实停机，请改为 false。
cfg.time.yearCyclic   = 'day';            % SOC 循环周期：'day' 逐日闭合（默认，与典型日模型口径一致）
                                         %                'month' 逐月闭合（允许跨日搬运电量，更乐观）
                                         %                'year'  整年闭合（自由度最大，最乐观）
                                         %   该设置同时作用于 full_year 模式 和 对典型日最优配置的
                                         %   全年核准；默认 'day' 使「典型日口径」与「全年核准口径」
                                         %   只差「时域压缩」一项，二者之差即代表典型日模型的保真度。
cfg.time.weekMode     = 'auto';          % 典型周选取：'auto' 自动选最具代表性一周 | 1..52 指定第几周

%% ==================== 2. 投资与技术经济参数（经典值，按需替换）====================
%--------------------------------------------------------------------------
%  ★ 2a. 成本计价口径（本轮新增：分档单价）
%     cfg.cost.mode = 'flat'    用下面各资产的「常数单价」（capex / capexP / capexE）
%                               —— 改动前的旧口径，便于与历史结果纵向对照。
%                   = 'tiered' 用下面各资产的「分档单价表」（tier / tierP / tierE）
%                               —— 单位投资单价 p = 按容量在分档表上分段线性插值，
%                                  投资额 = 容量 x p。
%     两点必须记住：
%       (1) 两个口径都由 gopt_unit_price 这一个函数实现，内层调度、外层适应度、
%           报表、出图、自检全部调用它 —— 绝不会出现「适应度一套、报表另一套」；
%       (2) tiered 时 capex / capexP / capexE 那几个数**不参与计算**，只作为 flat
%           口径的备用值与对照值（保留是为了随时能一键回退）。
%     分档表只对 光伏 / 风电 / 储能功率 / 储能容量 四项生效。厂内自发电**没有分档表**
%     （按用户指定恒为常数单价 400 元/kW），因此无论 mode 取什么都按常数单价算。
%--------------------------------------------------------------------------
cfg.cost.mode = 'tiered';

% ---- 2a-2. 分档跳变点的上界护栏（★ 本轮新增）----
% 分档表按「容量 >= 倒数第二行档位时取最后一行的单价」实现，于是**封顶档位处单价会
% 向下跳变**（本表：风电 −5.1%、储能容量 −2.9%、储能功率 −2.3%、光伏 0%）。
% 如果搜索上界正好等于该档位，优化器会稳定地坐在这个「价格悬崖」上 —— 结论由这条口径的
% 边界决定，而不是由经济性决定。所以程序在启动时会**直接报错拦下来**（见
% gopt_check_tier_ub），并给出两种修法：把表最后两行改成同值，或把上界挪开一点。
% 确实需要保留那个上界（例如工程上就是这么定的）时，把本项设为 true 放行，
% 程序会改为打印警告并在日志里点名是哪一维。
cfg.cost.allowTierEdgeBound = false;

%--------------------------------------------------------------------------
%  ★ 2b. 分档单价表（tiered 口径的唯一数据源；取自 BasicDataTables.xlsx，单价已含税）
%     格式：每行一档 [ 容量档位 , 该档位处的投资单价 ]，两列对齐，直接照着加减行即可。
%       · 第 1 列 = 容量档位 [MW]（储能容量那一张是 [MWh]），必须严格递增；
%       · 第 2 列 = 该档位处的单位投资单价 [元/kW]（储能容量那一张是 [元/kWh]）；
%       · 档位数不限，增删档位只改这里，程序会自动适配（gopt_unit_price）。
%
%     取值规则（gopt_unit_price 唯一实现，改动成本公式只需改那一个函数）：
%       · 容量 <= 表中【倒数第二行】的档位（本表 = 500）：
%             以各档位为结点做**分段线性插值** -> 单价随容量连续变化（一条折线）；
%       · 容量 >= 该档位（>= 500 MW / MWh）：
%             直接取【最后一行（20000 档）】的单价，不再插值、不外推。
%     ⚠ 因此 500 处有一个「单点跳变」（第 7 行单价 -> 第 8 行单价），这是按你指定的
%       「≥500 按 20000 档」实现的。若想让 500~20000 之间也线性过渡，
%       把 gopt_unit_price 里标了「TOPT」的那个分支去掉即可（该处有明确注释）。
%
%     数据来源对照（改数据时按这一列去 BasicDataTables.xlsx 找表）：
%       光伏装机  ->  工作表 PVCost       （表头「光伏装机（MW）」）
%       风电装机  ->  工作表 WindCost     （表头「风电装机（MW）」）
%       储能功率  ->  工作表 BatteryPCS   （表头「储能功率（MW）」）
%       储能容量  ->  工作表 BatteryCost  （表头「储能能量（MWh）」）
%     8 档对应的档位点统一是 0 / 6 / 20 / 50 / 100 / 200 / 500 / 20000，
%     含义是「装机规模越大、单位造价越低」的规模效应。
%--------------------------------------------------------------------------

% ---- 光伏 ----
cfg.cost.pv.capex     = 3800;    % 元/kW  常数单价（仅 cfg.cost.mode = 'flat' 时生效）
cfg.cost.pv.life      = 25;      % 年     运行寿命
cfg.cost.pv.opexRate  = 0.01;    % -      年运维费 / 初始投资
cfg.cost.pv.tier      = [ ...    % [档位 MW , 单价 元/kW]（仅 mode = 'tiered' 时生效）
        0    3500
        6    3200
       20    3100
       50    3000
      100    3000
      200    3000
      500    3000
    20000    3000 ];

% ---- 风电 ----
cfg.cost.wt.capex     = 6000;    % 元/kW  常数单价（仅 mode = 'flat' 时生效）
cfg.cost.wt.life      = 20;      % 年
cfg.cost.wt.opexRate  = 0.02;    % -      年运维费 / 初始投资
cfg.cost.wt.tier      = [ ...    % [档位 MW , 单价 元/kW]
        0    4719.000
        6    4611.750
       20    4504.500
       50    4397.250
      100    4343.625
      200    4290.000
      500    4182.750
    20000    3968.250 ];

% ---- 储能（功率与容量分开计价，两张表各自独立分档）----
cfg.cost.ess.capexP   = 1000;     % 元/kW  功率常数单价（仅 mode = 'flat' 时生效）
cfg.cost.ess.capexE   = 400;      % 元/kWh 容量常数单价（仅 mode = 'flat' 时生效）
cfg.cost.ess.life     = 10;       % 年
cfg.cost.ess.opexRate = 0.01;     % -      年运维费 / 初始投资
cfg.cost.ess.tierP    = [ ...     % 功率分档表 [档位 MW , 单价 元/kW]（表 BatteryPCS）
        0     600
        6     500
       20     480
       50     470
      100     460
      200     450
      500     440
    20000     430 ];
cfg.cost.ess.tierE    = [ ...     % 容量分档表 [档位 MWh , 单价 元/kWh]（表 BatteryCost）
        0     900
        6     850
       20     800
       50     760
      100     740
      200     720
      500     700
    20000     680 ];
%  ⚠ 这两张表各自独立分档，不要合并：储能功率用的是「元/kW（PCS 变流器）」，
%    储能容量用的是「元/kWh（电芯）」，量纲不同、档位含义也不同。

% ---- 厂内自发电（★ 本轮新增）----
%  ⚠ 本轮（分档单价改造）：厂内自发电**没有**分档单价表，按用户指定恒为常数单价
%    —— 无论 cfg.cost.mode 取 'flat' 还是 'tiered'，它都只按下面的 capex 计。
%    原因：BasicDataTables.xlsx 里没有自发电机组的造价分档表；且它的度电成本远低于
%    购电，放开分档会把这个维度变成「容量越大越便宜」，进一步放大「全建自发电」的
%    结论（本来就已经是这个结论了，见 Readme 的本轮改动说明）。若要改成分档，
%    在下面加一个 cfg.cost.gen.tier 即可 —— gopt_unit_price 会自动识别并生效。
%  自发电的成本由「两块」构成，两块都进目标函数，但走不同的通道、不重复计算：
%    (1) 投资侧：单位投资 x 额定容量，按 CRF 年化后计入「年化投资成本」
%        —— 与光伏 / 风电 / 储能完全同一个口径（见 gopt_annual_capex）；
%    (2) 运行侧：每发一度电付一份燃料+运维费，计入「年化运行成本」
%        —— 由内层 MILP 支付，**只对实际发出的电量计费，弃掉的部分不付费**。
%  报表里再额外单列「自发电度电成本」= (年化投资 + 年运行费) / 年实发电量，
%  以及它的两个拆分项，便于与光伏 / 风电 / 购电比价。
%--------------------------------------------------------------------------
%  ⚠ 一个必须分清的口径（读结果时最容易混淆的地方）：
%    · 装机层（外层，比的是「全成本」）：
%        自发电 ≈ 0.2097 元/kWh < 光伏 0.4001 < 风电 0.4285 < 购电 0.5995
%        => 值得优先建自发电。
%    · 调度层（内层，比的是「边际成本」）：
%        光伏/风电 = 0（建都建了，发一度电不再花钱）
%        自发电   = varCost（每发一度都要烧燃料）
%        => 有盈余时**先弃自发电、最后弃光伏风电**（正是「不使用高成本电量、
%           保留低成本电量」的经济学含义，不需要任何人为优先级规则）。
%    两者不矛盾：便宜的是「建」，贵的是「每发一度的燃料」。副作用是自发电
%    会有一部分被弃，实际利用率低于标幺曲线给出的等效满发小时数，因此**实际
%    度电成本会高于 0.2097** —— 报表同时给出实发量与按实发折算的度电成本。
cfg.cost.gen.capex    = 400;     % 元/kW  单位投资（初始投资）
cfg.cost.gen.life     = 25;      % 年     运行寿命
cfg.cost.gen.opexRate = 0.02;    % -      年运维费 / 初始投资
cfg.cost.gen.varCost  = 0.1;     % 元/kWh 运行成本（燃料 + 变动运维），按实际发电量计
                                 %   取 0 则自发电只承担投资成本（边际为零）；
                                 %   取大值会让自发电在盈余时刻更容易被弃。
                                 %   本算例：CRF(6%,25)+2% = 0.098227
                                 %          -> 400 x 0.098227 = 39.29 元/(kW·年)
                                 %          -> 投资折算 39.29 / 4035 h = 0.0097 元/kWh

% ---- 共性 ----
cfg.cost.discountRate = 0.06;    % 折现率 i，用于资金回收系数 CRF

%% ==================== 3. 储能技术参数 ====================
cfg.ess.etaCh         = 0.93;    % 充电效率
cfg.ess.etaDis        = 0.93;    % 放电效率
cfg.ess.socMin        = 0.05;    % SOC 下限（占储能容量）
cfg.ess.socMax        = 0.95;    % SOC 上限（占储能容量）
cfg.ess.socInit       = 0.50;    % 循环起止 SOC（占储能容量），仅 fixInitialSoc=true 时生效
cfg.ess.fixInitialSoc = false;   % false => SOC 周期闭合但起点自由（经济最优，推荐）
                                 % true  => 每个循环周期起始 SOC 强制 = socInit
cfg.ess.selfDis       = 2e-4;    % 自放电率（每小时）
cfg.ess.durationSeed  = 2;       % h，储能时长维度的「参考值」，用于初始种群撒点（不影响最优性）
cfg.ess.cycleMode     = 'day';         % 储能 SOC 循环方式（仅典型日模式生效）：
                                 %   'day'     每个典型日首末 SOC 严格闭合（默认，最保守）。
                                 %             把储能建模为「每天最多满充满放一次」的日循环运行，
                                 %             与 cfg.time.yearCyclic='day' 的全年口径完全一致，
                                 %             因此 cfg.out.fullYearCheck 给出的偏差只反映时域压缩误差。
                                 %   'neutral' 每个周期起始 SOC 自由 + 年加权能量中性约束。
                                 %             允许跨日搬运电量，但会重复利用跨日自由度，
                                 %             使成本偏乐观约 7%（不建议用于最终结论）。
                                 % 注意：本项只接受 'day' / 'neutral' 两个值；填其它字符串不会报错，
                                 %       但判据 strcmp(...,'neutral') 不成立，会静默退化为 'day' 行为。
                                 % 全年模式（full_year）下由 cfg.time.yearCyclic 决定循环周期，
                                 % 本项不生效。
                                 % 口径一致性：要让「典型日模型」与「全年核准」可比，须两个设置取同一
                                 % 口径——都逐日闭合 = yearCyclic 'day' + cycleMode 'day'（推荐），
                                 % 或都允许跨日搬运 = yearCyclic 'year' + cycleMode 'neutral'。

% ---- 储能循环寿命（与储能寿命直接关联）----
%  为什么需要它：储能的寿命并不是固定的 10 年，而是被「充放循环次数」消耗掉的。
%  同一个储能配置，调度越激进（每天充放越深、循环越频繁），循环寿命越早耗尽，
%  年化投资成本就越高。把寿命写成常数，等于默认「怎么用都不影响换电池的钱」，
%  会让模型系统性偏爱「配大储能、深度循环」的方案。
%  开启本组参数后，储能寿命不再外生给定，而是由本次最优调度反算出来：
%      年等效循环次数 = 年放电量 / 储能额定容量            （由 cycleBasis 决定算法）
%      循环折算寿命   = 循环寿命(次) / 年等效循环次数       （年）
%      实际寿命       = min(日历寿命 cfg.cost.ess.life, 循环折算寿命)   （由 lifeMode 决定）
%  再以「实际寿命」重算资金回收系数 CRF，进而改变年化投资成本。
%  为什么这样算不会引入循环依赖：内层 MILP 的目标只含购售电、与投资成本无关，
%  所以同一个容量点上「调度 -> 年等效循环次数 -> 寿命 -> 年化投资成本」是
%  单向一次算清的，不需要迭代求解。
%  注意 lifeMode 会同时改变外层 PSO 的目标函数，因此也改变搜索到的最优配置。
cfg.ess.cycleLife   = 6000;      % 次   额定循环寿命（一般指容量衰减到 80% 时的累计循环数）
cfg.ess.lifeMode    = 'cycle_min'; % 储能寿命口径：
                                 %   'cycle_min' 取「日历寿命」与「循环折算寿命」较小者（默认，推荐）
                                 %   'cycle'     只用循环折算寿命（不设日历寿命上限）
                                 %   'calendar'  只用日历寿命 = 关闭耦合（等价于旧行为）
cfg.ess.cycleBasis  = 'discharge'; % 年等效循环次数的定义：
                                 %   'discharge'  年放电量 / 额定容量（默认：一次完整放电记 1 次）
                                 %   'throughput' （年充电量+年放电量）/（2 x 额定容量）
                                 %   'charge'     年充电量 / 额定容量
cfg.ess.lifeFloor   = 1;         % 年   循环折算寿命的下限护栏。极端调度（储能配得很小又深度
                                 %      循环）可能算出远小于 1 年的寿命，此时资金回收系数
                                 %      CRF = i(1+i)^N/((1+i)^N-1) 在 N -> 0 时发散，数值上不可用；
                                 %      故强制寿命不低于该值，并在日志里明确标注「已触发下限」。

