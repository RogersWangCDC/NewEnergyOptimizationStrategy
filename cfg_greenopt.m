cfg.pso.stageA.expand  = true;% 阶段 A 是否也做边界诊断与外扩

% ---- 5f. 局部精修（在 PSO 收敛之后）----
cfg.pso.localRefine = true;   % PSO 收敛后做局部精修，显著提升最优解精度
cfg.pso.refineStep0 = 0.15;   % 精修初始步长 = 该系数 x 搜索区间宽度
cfg.pso.refineTolRel = 2e-3;  % 精修终止步长 = 该系数 x 搜索区间宽度
cfg.pso.refineMethod = 'hj';  % 'hj'（默认）Hooke-Jeeves 式加速步长 + 随机方向试探
