cfg.pso.c1End        = 0.5;   % c1 末值（个体学习减弱）
cfg.pso.c2End        = 2.5;   % c2 末值（群体学习增强）
cfg.pso.constriction = 0;     % 收缩因子 χ（0 = 不用；填 0.729 即标准收缩 PSO）

% ---- 5e. 两阶段搜索（★ 本轮新增）----
% 预算分配的依据（实测，供你按机器性能调整）：
%   · 阶段 A 的典型日内层（288 h）单次求解约 0.1 s，跑上万次也只要十几分钟，
