cfg.pso.refineNM     = true;  % 精修结束后再用 Nelder-Mead（fminsearch）收尾一次
cfg.pso.refineMaxEval= 60;    % 局部精修的评估次数上限（防止精修把搜索预算吃掉）；
                              % 实测单次全年评估约 5~10 s，故 60 次约 10 分钟。
                              % 注意这是「护栏」而不是「目标」：实测 40 次时精修已在
                              % 收敛末端（改善仅 4.4 万元 = 0.1%），故不必取得太大。

% ---- 5g. 稳定性诊断（可选，很费时）----
cfg.pso.multiRun     = 0;     % >1 时用不同随机种子独立跑这么多次，取最优并输出
