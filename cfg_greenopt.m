%% ==================== 5. 外层 PSO（含局部精修 + 边界诊断 + 两阶段搜索）====================
%--------------------------------------------------------------------------
%  ★ 为什么要改这一节（本轮调优的原因）
%  上一版的最优解同时贴在上下界上（光伏 = 50 MW = 上界、风电 = 2 MW = 下界），
%  这是「边界卡死 + 早熟收敛」的典型症状：搜索上界把真解挡在外面，而种群又早早
%  把所有粒子拉到同一点，之后每一代都在原地打转。本节新增四组机制对应解决：
%    (1) 边界诊断与自动外扩 —— 解贴上界就自动把上界推远，再重启一轮；
%    (2) 初始化升级           —— 拉丁超立方 + 对立学习 + 混沌映射；
%    (3) 多种群小生境 + 逃逸   —— 拆子群独立演化，停滞时扰动而不是直接早停；
%    (4) 两阶段搜索           —— 先用典型日口径大规模粗搜，再用全年口径精搜。
%--------------------------------------------------------------------------
%  ⚠ 两阶段搜索（推荐开启）怎么理解：**双层嵌套结构一点没变**，只是让「内层 MILP」
%  换两种时间尺度各跑一遍：
%    · 阶段 A（粗搜）：把全年 8760 h 压缩成 searchK 个典型日（默认 12 x 24 = 288 h），
%      内层 MILP 规模小一到两个数量级，单次评估快得多，于是可以用几千次评估把
%      「哪一片区域可能是最优」摸清楚；
%    · 阶段 B（精搜）：换回目标口径（cfg.time.mode，默认 full_year 的 8760 h），
%      在以阶段 A 最优解为中心的收缩区间里做精细搜索 —— 全年单次评估约 1 分钟，
%      只能负担一百多次，所以必须先用阶段 A 把范围收窄。
%  为什么不用「搜索阶段解 LP、验证阶段解 MILP」：购售电互斥的 0-1 变量不能去掉。
%  本数据集有 89 个小时「售电价 > 购电价」（最大倒挂 0.0298 元/kWh），去掉互斥后
%  LP 会在这些小时同时买电与售电套利，凭空造出上亿元/年的假收益，搜索会彻底跑偏。
%  （搜索阶段可以安全去掉的是「充放电互斥」0-1，见第 6 节 cfg.milp.cdBinary。）
%--------------------------------------------------------------------------
cfg.pso.nPop       = 5;      % 粒子数（阶段 B，目标口径）
cfg.pso.maxIter    = 3;       % 最大迭代次数（阶段 B）
                              %   ⚠ 阶段 B 每评估一次就解一次全年 8760 h 的 MILP。
                              %     实测：关掉充放电互斥 0-1 后单次约 5~10 s（旧版约 80 s），
                              %     故 8 代 x 12 粒子 = 96 次评估约 15 分钟。
                              %     想更彻底就调到 15~20（每个代数约 2 分钟）；想更快就调到 6。
cfg.pso.wMax       = 0.9;     % 惯性权重上限
cfg.pso.wMin       = 0.4;     % 惯性权重下限
cfg.pso.c1         = 1.5;     % 个体学习因子（起始值，走自适应时按 c1End 递减）
cfg.pso.c2         = 1.5;     % 群体学习因子（起始值，走自适应时按 c2End 递增）
cfg.pso.vMaxRate   = 1.1;     % 速度上限 = vMaxRate x 搜索区间宽度
cfg.pso.seed       = 2026;    % 随机种子（保证可复现）
cfg.pso.stallIter  = 10;      % 连续多少代无显著改进则进入「逃逸」流程
cfg.pso.tolCost    = 1e-4;    % 相对改进阈值（停滞判定）
cfg.pso.useParallel = false;  % true => parfor 并行评估（需 Parallel Computing Toolbox）
cfg.pso.cacheEval  = true;    % 缓存已评估点，避免重复调用内层 MILP

% ---- 5a. 边界诊断与自动外扩（★ 本轮新增，直接针对「解贴界」）----
cfg.pso.boundCheck   = true;  % 最优解贴上/下界时，自动外扩该维上界后重启一轮
cfg.pso.boundFrac    = 0.02;  % 贴界判据：距界 < boundFrac x 该维区间宽度
cfg.pso.expandFactor = 1.5;   % 外扩倍数（新上界 = 原上界 x 该系数）
cfg.pso.expandMax    = 1;     % 最多外扩重启轮数
cfg.pso.expandFree   = [true; true; true; false; false];
                              % 哪些维度允许自动外扩（顺序同 s）：
                              %   光伏 / 风电 / 储能功率可外扩；
                              %   储能时长锁 1~8 h（工程界）、自发电容量锁 0~100 MW
                              %   （用户指定的工程上限，不能靠算法自动突破）。
                              %   ⚠ 自发电这一维一定不要设成 true：它比购电便宜得多，
                              %     解天然会往上界跑，放开外扩会一路加容量到无意义。

% ---- 5b. 初始化（★ 本轮新增）----
cfg.pso.initMode     = 'lhs_obl';  % 'random' 纯随机（旧行为）
                                   % 'lhs'    拉丁超立方（分层均匀）
                                   % 'lhs_obl'（默认）拉丁超立方 + 对立学习
                                   % 'chaos'  混沌映射（Logistic）
cfg.pso.keepSeeds    = true;       % 是否保留原有的 8 个确定性种子点（推荐 true）

% ---- 5c. 多种群小生境 + 逃逸重启（★ 本轮新增）----
cfg.pso.multiSwarm   = 2;     % 子群个数（1 = 关闭多种群，退化为标准 PSO）
cfg.pso.exchangeIt   = 8;     % 每多少代做一次子群间的群体最优交换
cfg.pso.resetFrac    = 0.10;  % 每代把「最差的这一比例粒子」重新撒点（0 = 关闭）
cfg.pso.escapeTries  = 2;     % 停滞时先做几次「逃逸扰动」才允许真早停
